#!/usr/bin/env python
"""Generate ``layer1/FontCJK.h`` from a CJK TTF/OTF font.

The internal GUI (Ortho object list, popup menus, HUD) renders text with
PyMOL's font system.  The bundled bitmap fonts only cover Latin-1, so Chinese
renders as ``?``.  This script subsets a CJK font (default: Noto Sans SC, an
OFL font) to the characters we need and emits it as a C byte array, following
the same pattern as the existing ``layer1/FontTTF2.h``.

Usage::

    python tools/gen_font_header.py \
        --font "C:\\Windows\\Fonts\\Noto Sans SC (TrueType).otf" \
        --output layer1/FontCJK.h

The subset covers: ASCII, Latin-1, CJK punctuation, full-width forms, all
GB2312 characters (so arbitrary Chinese object names render), and every
character used by the shipped translation catalogs.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_OUTPUT = ROOT / 'layer1' / 'FontCJK.h'
SYMBOL = 'TTF_NotoSansSC'


def build_charset(catalog_paths=()):
    chars = set()
    for start, end in ((0x20, 0x7E), (0xA0, 0xFF), (0x3000, 0x303F), (0xFF00, 0xFFEF)):
        chars.update(chr(c) for c in range(start, end + 1))
    # every Unicode char that GB2312 can encode (6763 common Han chars)
    for cp in range(0x4E00, 0xA000):
        ch = chr(cp)
        try:
            ch.encode('gb2312')
        except UnicodeEncodeError:
            continue
        chars.add(ch)
    # every char actually used by the translation catalogs
    for path in catalog_paths:
        try:
            data = json.loads(pathlib.Path(path).read_text(encoding='utf-8'))
        except Exception:
            continue
        for key, value in (data.get('strings') or {}).items():
            if isinstance(key, str):
                chars.update(key)
            if isinstance(value, str):
                chars.update(value)
            elif isinstance(value, dict):
                for item in value.values():
                    if isinstance(item, str):
                        chars.update(item)
    return chars


def subset_font(font_path, out_path, chars):
    from fontTools import subset

    options = subset.Options()
    options.layout_features = ['*']
    options.notdef_outline = True
    options.name_IDs = ['*']
    options.recalc_bounds = True
    options.glyph_names = False

    font = subset.load_font(str(font_path), options)
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=[ord(c) for c in chars])
    subsetter.subset(font)
    subset.save_font(font, str(out_path), options)


def emit_header(data, output, symbol, source_name):
    lines = [
        '/* -------------------------------------------------------------------',
        ' * Embedded CJK font for the internal GUI (object list, popups, HUD).',
        ' *',
        ' * Generated by tools/gen_font_header.py from:',
        ' *   %s' % source_name,
        ' *',
        ' * The source font is Noto Sans SC, Copyright 2014-2021 Adobe',
        ' * (http://www.adobe.com/), licensed under the SIL Open Font License,',
        ' * Version 1.1.  Subsetted for PyMOL use.',
        ' *',
        ' * Do not edit by hand.  Regenerate with tools/gen_font_header.py.',
        ' * -------------------------------------------------------------------',
        ' */',
        '',
        '#pragma once',
        '',
        'static unsigned char %s_dat[] = {' % symbol,
    ]
    for i in range(0, len(data), 16):
        chunk = data[i:i + 16]
        lines.append('  ' + ','.join('0x%02x' % b for b in chunk) + ',')
    lines.append('};')
    lines.append('')
    lines.append('static unsigned int %s_len = %d;' % (symbol, len(data)))
    lines.append('')
    pathlib.Path(output).write_text('\n'.join(lines), encoding='utf-8')


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--font', required=True, help='source CJK TTF/OTF')
    parser.add_argument('--output', default=str(DEFAULT_OUTPUT))
    parser.add_argument('--symbol', default=SYMBOL)
    parser.add_argument('--catalog', nargs='*',
                        default=[str(ROOT / 'data' / 'i18n' / 'zh_CN.json')])
    args = parser.parse_args(argv)

    font_path = pathlib.Path(args.font)
    if not font_path.is_file():
        print('error: font not found: %s' % font_path, file=sys.stderr)
        return 2

    chars = build_charset(args.catalog)
    print('charset: %d characters' % len(chars))

    import tempfile
    with tempfile.TemporaryDirectory() as tmp:
        subset_path = pathlib.Path(tmp) / 'subset.ttf'
        subset_font(font_path, subset_path, chars)
        data = subset_path.read_bytes()

    print('subset font: %.2f MB' % (len(data) / 1048576.0))
    emit_header(data, args.output, args.symbol, font_path.name)
    print('wrote %s (%.1f MB)' % (args.output, pathlib.Path(args.output).stat().st_size / 1048576.0))
    return 0


if __name__ == '__main__':
    sys.exit(main())
