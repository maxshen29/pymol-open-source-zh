#!/usr/bin/env python
"""Add the internal-GUI HUD strings to the catalog and generate layer1/HudTr.h.

The HUD (``Mouse Mode``, ``Buttons``, ``Picking``, ``Frame``, ...) is drawn by
C++ with hard-coded English literals in ``ButMode.cpp``.  ``TextTr()`` looks a
string up in the table generated here, using ``$PYMOL_LANG`` to decide whether
to translate.

Usage::

    python tools/gen_hud_header.py
"""

from __future__ import annotations

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CATALOG = ROOT / 'data' / 'i18n' / 'zh_CN.json'
OUTPUT = ROOT / 'layer1' / 'HudTr.h'

#: English HUD literal -> Simplified Chinese
HUD_STRINGS = {
    'Mouse Mode ': '鼠标模式 ',
    'Buttons': '鼠标键',
    '    L    M    R  Wheel': '    左   中   右  滚轮',
    'Keys': '键盘',
    ' SnglClk': ' 单击',
    ' DblClk': ' 双击',
    'Picking ': '拾取 ',
    'Atoms (and Joints)': '原子（及键）',
    'Selecting ': '选择 ',
    'Atoms': '原子',
    'Residues': '残基',
    'Chains': '链',
    'Segments': '片段',
    'Objects': '对象',
    'Molecules': '分子',
    'C-alphas': 'Cα',
    'Frame ': '帧 ',
    'State ': '状态 ',
    'Hz ': 'Hz ',
}


def update_catalog():
    data = json.loads(CATALOG.read_text(encoding='utf-8'))
    strings = data.setdefault('strings', {})
    added = 0
    for en, zh in HUD_STRINGS.items():
        if strings.get(en) != zh:
            strings[en] = zh
            added += 1
    data['strings'] = dict(sorted(strings.items(), key=lambda kv: kv[0].lower()))
    CATALOG.write_text(json.dumps(data, indent=2, ensure_ascii=False) + '\n',
                       encoding='utf-8')
    return added


def _c_literal(text):
    out = text.replace('\\', '\\\\').replace('"', '\\"')
    return '"%s"' % out


def _c_utf8_literal(text):
    """Emit *text* as UTF-8 bytes using \\xNN escapes.

    MSVC decodes source files in the system codepage unless /utf-8 is set, and
    encodes narrow literals in that same codepage.  Escaping every byte makes
    the runtime bytes UTF-8 (what PyMOL's text renderer expects) regardless of
    the compiler's charset settings.
    """
    return '"' + ''.join('\\x%02x' % b for b in text.encode('utf-8')) + '"'


def write_header():
    lines = [
        '/* -------------------------------------------------------------------',
        ' * Internal-GUI HUD strings (mouse mode, buttons, picking, frame rate).',
        ' *',
        ' * Generated by tools/gen_hud_header.py from data/i18n/zh_CN.json.',
        ' * Do not edit by hand.  TextTr() in Text.cpp looks a string up here',
        ' * when $PYMOL_LANG selects a Chinese language.',
        ' * -------------------------------------------------------------------',
        ' */',
        '',
        '#pragma once',
        '',
        'struct HudTrEntry {',
        '  const char* en;',
        '  const char* zh;',
        '};',
        '',
        'static const HudTrEntry HudTrTable[] = {',
    ]
    for en, zh in HUD_STRINGS.items():
        lines.append('  {%s, %s},' % (_c_literal(en), _c_utf8_literal(zh)))
    lines.append('};')
    lines.append('')
    lines.append('static const unsigned int HudTrCount = %d;' % len(HUD_STRINGS))
    lines.append('')
    OUTPUT.write_text('\n'.join(lines), encoding='utf-8')


def main():
    added = update_catalog()
    write_header()
    print('catalog: %d HUD entries added/updated' % added)
    print('wrote', OUTPUT)
    return 0


if __name__ == '__main__':
    sys.exit(main())
